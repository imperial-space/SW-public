    private void RebuildSelected()
    {
        OffersContainer.DisposeAllChildren();
        if (_management || _archive || _state == null || _selected == null)
        {
            SelectedName.Text = Loc.GetString("trading-ui-select-item");
            SelectedName.FontColorOverride = null;
            SelectedPreview.DisposeAllChildren();
            SelectedStats.SetMarkup(string.Empty);
            CreateBuyOrderButton.Disabled = true;
            return;
        }

        var item = _state.Items.FirstOrDefault(value => value.CommodityId == _selected.Value);
        if (item == null)
            return;

        var selectedOffer = _selectedOffer is { } selectedOfferId
            ? _state.Offers.FirstOrDefault(offer =>
                offer.Id == selectedOfferId &&
                offer.CommodityId == item.CommodityId)
            : null;
        if (_selectedOffer != null && selectedOffer == null)
        {
            _selectedOffer = null;
            _updateSelectedPrice = true;
        }

        SelectedName.Text = selectedOffer?.DisplayName ?? item.DisplayName;
        SelectedName.FontColorOverride = item.IsDamagedEquipment ? Color.FromHex("#e65353") : null;
        SelectedPreview.DisposeAllChildren();
        SelectedPreview.AddChild(selectedOffer == null
            ? CreateItemPreview(item, new Vector2(96, 96))
            : CreateItemPreview(
                selectedOffer.ProductEntity,
                selectedOffer.PreviewEntity,
                new Vector2(96, 96),
                selectedOffer.CommodityId));
        if (_updateSelectedPrice)
        {
            BuyPrice.Text = (selectedOffer?.Price ?? item.LowestSellPrice)?.ToString() ?? string.Empty;
            _updateSelectedPrice = false;
        }
        SelectedStats.SetMarkup(_state.IsPublic
            ? Loc.GetString("trading-ui-public-offer-count", ("count", item.SellOfferCount))
            : Loc.GetString(
                "trading-ui-offer-counts",
                ("sellCount", item.SellOfferCount),
                ("buyCount", item.BuyOfferCount)));
        CreateBuyOrderButton.Disabled = !_state.IsOwner;

        var offers = _state.Offers
            .Where(offer => offer.CommodityId == item.CommodityId)
            .OrderBy(offer => offer.Side)
            .ThenBy(offer => offer.Side == TradingOfferSide.Sell ? offer.Price : -offer.Price);
        foreach (var offer in offers)
        {
            var row = new BoxContainer
            {
                Orientation = BoxContainer.LayoutOrientation.Horizontal,
                HorizontalExpand = true,
                Margin = new Thickness(0, 0, 0, 3),
            };
            row.AddChild(new Label
            {
                Text = GetOfferSideText(offer.Side),
                MinWidth = 54,
            });
            var selectOffer = new Button
            {
                Text = offer.ParticipantName,
                HorizontalExpand = true,
                ClipText = true,
            };
            selectOffer.OnPressed += _ =>
            {
                _selectedOffer = offer.Id;
                _updateSelectedPrice = true;
                OnSelectOffer?.Invoke(offer.Id);
            };
            row.AddChild(selectOffer);

            if (offer.Side == TradingOfferSide.Buy &&
                offer.ParticipantKind == TradingParticipantKind.Guild)
            {
                row.AddChild(new Label
                {
                    Text = offer.Price.ToString(),
                    MinWidth = 76,
                    Align = Label.AlignMode.Center,
                    VAlign = Label.VAlignMode.Center,
                });
            }
            else
            {
                var action = new Button
                {
                    Text = offer.Price.ToString(),
                    MinWidth = 76,
                    Disabled = (!_state.IsOwner &&
                                !(_state.IsPublic && offer.Side == TradingOfferSide.Sell)) ||
                               offer.IsOwn ||
                               offer.Side == TradingOfferSide.Sell && offer.Price > _state.Balance,
                    StyleBoxOverride = offer.Side == TradingOfferSide.Sell
                        ? CreateActionButtonStyle("#c79612", "#f0d36f")
                        : CreateActionButtonStyle("#b13a3a", "#e66b63"),
                };
                action.Label.FontColorOverride = Color.White;
                action.OnPressed += _ =>
                {
                    if (offer.Side == TradingOfferSide.Sell)
                        OnBuyOffer?.Invoke(offer.Id);
                    else
                        OnSellOffer?.Invoke(offer.Id);
                };
                row.AddChild(action);
            }

            if (offer.IsOwn)
            {
                var cancel = new Button { Text = "×", MinWidth = 28 };
                cancel.OnPressed += _ => OnCancelOffer?.Invoke(offer.Id);
                row.AddChild(cancel);
            }
            OffersContainer.AddChild(row);
        }
    }

    private void CreateSelectedBuyOrder()
    {
        if (_state is not { IsOwner: true } || _selected == null)
            return;

        if (!TryParsePrice(BuyPrice.Text, out var price))
        {
            ShowInvalidOfferPricePopup();
            return;
        }

        OnCreateBuyOffer?.Invoke(_selected.Value, price);
    }

    private void RebuildManagement()
    {
        ManagedOffersContainer.DisposeAllChildren();
        PendingSalesContainer.DisposeAllChildren();
        StoredItemsContainer.DisposeAllChildren();
        if (_state == null)
            return;

        var ownOffers = _state.Offers.Where(offer => offer.IsOwn).ToList();
        if (ownOffers.Count == 0)
        {
            ManagedOffersContainer.AddChild(new Label
            {
                Text = Loc.GetString("trading-ui-no-active-offers"),
            });
        }

        foreach (var offer in ownOffers)
        {
            var row = CreateManagementRow(
                offer.ProductEntity,
                offer.PreviewEntity,
                offer.CommodityId,
                offer.DisplayName,
                Loc.GetString(
                    "trading-ui-managed-offer-status",
                    ("side", GetOfferSideText(offer.Side)),
                    ("price", offer.Price)));
            var cancel = new Button
            {
                Text = Loc.GetString(offer.Side == TradingOfferSide.Sell
                    ? "trading-ui-cancel-and-collect-button"
                    : "trading-ui-cancel-button"),
                MinWidth = 150,
            };
            cancel.OnPressed += _ => OnCancelOffer?.Invoke(offer.Id);
            row.AddChild(cancel);
            ManagedOffersContainer.AddChild(row);
        }

        if (_state.PendingSales.Count == 0)
        {
            PendingSalesContainer.AddChild(new Label
            {
                Text = Loc.GetString("trading-ui-no-pending-sales"),
            });
        }

        foreach (var sale in _state.PendingSales)
        {
            var message = Loc.GetString(
                "trading-ui-pending-sale-entry",
                ("item", sale.ItemName),
                ("trader", sale.BuyerName),
                ("price", sale.Price));
            var row = new BoxContainer
            {
                Orientation = BoxContainer.LayoutOrientation.Horizontal,
                HorizontalExpand = true,
                Margin = new Thickness(4),
            };
            row.AddChild(new Label
            {
                Text = message,
                ToolTip = message,
                HorizontalExpand = true,
                ClipText = true,
                VerticalAlignment = VAlignment.Center,
            });
            var collect = new Button
            {
                Text = Loc.GetString("trading-ui-collect-sale-revenue-button"),
                MinWidth = 150,
            };
            collect.OnPressed += _ => OnCollectSaleRevenue?.Invoke(sale.Id);
            row.AddChild(collect);
            PendingSalesContainer.AddChild(row);
        }

        if (_state.StoredItems.Count == 0)
        {
            StoredItemsContainer.AddChild(new Label
            {
                Text = Loc.GetString("trading-ui-no-stored-items"),
            });
        }

        foreach (var stored in _state.StoredItems)
        {
            var row = CreateManagementRow(
                stored.ProductEntity,
                stored.Item,
                null,
                stored.DisplayName,
                Loc.GetString("trading-ui-received-from-order"));
            var collect = new Button
            {
                Text = Loc.GetString("trading-ui-collect-button"),
                MinWidth = 150,
            };
            collect.OnPressed += _ => OnCollectStoredItem?.Invoke(stored.Item);
            row.AddChild(collect);
            StoredItemsContainer.AddChild(row);
        }
    }

    private void RebuildArchive()
    {
        ArchiveContainer.DisposeAllChildren();
        if (_state == null)
            return;

        if (_state.Archive.Count == 0)
        {
            ArchiveContainer.AddChild(new Label
            {
                Text = Loc.GetString("trading-ui-empty-archive"),
                Margin = new Thickness(4),
            });
            return;
        }

        foreach (var message in _state.Archive.AsEnumerable().Reverse())
        {
            ArchiveContainer.AddChild(new Label
            {
                Text = message,
                ToolTip = message,
                HorizontalExpand = true,
                ClipText = true,
                Margin = new Thickness(4, 2),
            });
        }
    }

