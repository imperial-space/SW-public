        EntProtoId product,
        NetEntity? preview,
        Guid? commodityId,
        string displayName,
        string status)
    {
        var row = new BoxContainer
        {
            Orientation = BoxContainer.LayoutOrientation.Horizontal,
            HorizontalExpand = true,
            Margin = new Thickness(4),
        };
        row.AddChild(CreateItemPreview(product, preview, new Vector2(54, 54), commodityId));
        var labels = new BoxContainer
        {
            Orientation = BoxContainer.LayoutOrientation.Vertical,
            HorizontalExpand = true,
            VerticalAlignment = VAlignment.Center,
            Margin = new Thickness(8, 0),
        };
        labels.AddChild(new Label { Text = displayName, ClipText = true });
        labels.AddChild(new Label { Text = status, StyleClasses = { "LabelSubText" } });
        row.AddChild(labels);
        return row;
    }

    private void SubmitPrice(string text, Action<int>? action, bool allowZero = false)
    {
        if (!TryParsePrice(text, out var price, allowZero))
        {
            ShowInvalidOfferPricePopup();
            return;
        }

        action?.Invoke(price);
    }

    private void ShowInvalidOfferPricePopup()
    {
        _entities.System<PopupSystem>().PopupCursor(
            Loc.GetString("trading-ui-invalid-offer-price"),
            PopupType.SmallCaution);
    }

    private static bool TryParsePrice(string text, out int price, bool allowZero = false)
    {
        return int.TryParse(text, out price) && (price > 0 || allowZero && price == 0);
    }

    private Control CreateItemPreview(TradingMarketItemState item, Vector2 size)
    {
        return CreateItemPreview(item.ProductEntity, item.PreviewEntity, size, item.CommodityId);
    }

    private Control CreateItemPreview(
        EntProtoId product,
        NetEntity? preview,
        Vector2 size,
        Guid? commodityId)
    {
        if (preview is { } netEntity)
        {
            var view = new SpriteView
            {
                MinSize = size,
                SetSize = size,
                Stretch = SpriteView.StretchMode.Fill,
                HorizontalAlignment = HAlignment.Center,
                VerticalAlignment = VAlignment.Center,
                MouseFilter = Control.MouseFilterMode.Pass,
            };
            view.SetEntity(netEntity);
            view.OnKeyBindDown += args =>
            {
                if (args.Function != ContentKeyFunctions.ExamineEntity)
                    return;

                OnExamineItem?.Invoke(netEntity);
                args.Handle();
            };
            return view;
        }

        if (_prototypes.HasIndex(product))
        {
            var icon = new TextureRect
            {
                Texture = _entities.System<SpriteSystem>().GetPrototypeIcon(product).Default,
                MinSize = size,
                SetSize = size,
                Stretch = TextureRect.StretchMode.KeepAspectCentered,
                HorizontalAlignment = HAlignment.Center,
                VerticalAlignment = VAlignment.Center,
                MouseFilter = Control.MouseFilterMode.Pass,
            };
            icon.OnKeyBindDown += args =>
            {
                if (args.Function != ContentKeyFunctions.ExamineEntity)
                    return;

                if (commodityId is { } id)
                    OnExamineCommodity?.Invoke(id, product);
                args.Handle();
            };
            return icon;
        }

        return new Control
        {
            MinSize = size,
            SetSize = size,
        };
    }

    public EntityUid GetPrototypeExamineEntity(EntProtoId product)
    {
        if (_prototypeExamineEntities.TryGetValue(product, out var entity) &&
            _entities.EntityExists(entity))
        {
            return entity;
        }

        entity = _entities.SpawnEntity(product, MapCoordinates.Nullspace);
        _prototypeExamineEntities[product] = entity;
        return entity;
    }

    private static bool HasSection(TradingMarketItemState item, TradingMarketSection section)
    {
        return (item.Sections & section) != 0;
    }

    private void OnActiveHandChanged(string? _)
    {
        UpdateHeldItem();
    }

    private void OnHeldItemChanged(string _, EntityUid __)
    {
        UpdateHeldItem();
    }

    private void OnHandsAdded(Entity<HandsComponent> _)
    {
        UpdateHeldItem();
    }

    private void OnHandsRemoved()
    {
        UpdateHeldItem();
    }

    private void UpdateHeldItem()
    {
        var itemName = "—";
        var canOffer = false;
        if (_state is { IsOwner: true } &&
            _hands.GetActiveHandEntity() is { } held &&
            _entities.EntityExists(held) &&
            !_entities.HasComponent<VirtualItemComponent>(held) &&
            _entities.TryGetComponent<MetaDataComponent>(held, out var metadata))
        {
            itemName = metadata.EntityName;
            if (metadata.EntityPrototype?.ID is { } product &&
                _entities.HasComponent<ItemComponent>(held))
            {
                canOffer = true;
            }
        }

        if (_heldItemName != itemName)
        {
            _heldItemName = itemName;
            HeldItemName.SetMessage(
                Loc.GetString("trading-ui-held-item", ("item", itemName)),
                defaultColor: Color.White);
            HeldItemName.ToolTip = itemName;
        }

        UpdateHeldItemAvailability(canOffer);
    }

    private void UpdateHeldItemAvailability(bool canOffer)
    {
        CreateSellOfferButton.Disabled = !canOffer;
        CreateUnitSellOfferButton.Disabled = !canOffer;
        CreateHeldBuyOrderButton.Disabled = !canOffer;
    }

    public void OpenUnitSellWindow(TradingUnitSellOfferPreparedMessage message)
    {
        if (_state is not { IsOwner: true })
            return;

        _unitSellWindow?.Close();
        _unitSellRequest = message.RequestId;
        _unitSellWindow = new TradingUnitSellWindow(
            message.ItemName,
            message.Price,
            message.MaximumAmount);
        _unitSellWindow.OnConfirm += amount =>
        {
            if (_unitSellRequest is not { } requestId)
                return;

            _unitSellRequest = null;
            OnCreateUnitSellOffers?.Invoke(requestId, amount);
        };
        _unitSellWindow.OpenCentered();
    }

    private void OpenWithdrawWindow()
    {
        if (_state is not { IsOwner: true } || _currency == null)
            return;

        if (_withdrawWindow is { IsOpen: true })
        {
            _withdrawWindow.MoveToFront();
            return;
        }

        _withdrawWindow = new StoreWithdrawWindow();
        _withdrawWindow.OpenCentered();
        _withdrawWindow.CreateCurrencyButtons(new Dictionary<ProtoId<CurrencyPrototype>, FixedPoint2>
        {
            { _currency, _state.Balance },
        });
        _withdrawWindow.OnWithdrawAttempt += (_, _, amount) => OnWithdraw?.Invoke(amount);
    }

    private void OpenHelpWindow()
    {
        if (_helpWindow is { IsOpen: true })
        {
            _helpWindow.MoveToFront();
            return;
        }

        _helpWindow = new TradingHelpWindow();
        _helpWindow.OpenCentered();
    }

    private static string GetOfferSideText(TradingOfferSide side)
    {
        return Loc.GetString(side == TradingOfferSide.Sell
            ? "trading-ui-sell-offer"
            : "trading-ui-buy-order");
    }

    private void UpdateColumns()
    {
        ItemsGrid.Columns = Math.Max(1, (int) (ItemsGrid.Width / 185));
    }

    public override void Close()
    {
        StopTrackingHands();

        base.Close();
        _withdrawWindow?.Close();
        _unitSellWindow?.Close();
        _helpWindow?.Close();

        foreach (var entity in _prototypeExamineEntities.Values)
        {
            if (_entities.EntityExists(entity))
                _entities.QueueDeleteEntity(entity);
        }

        _prototypeExamineEntities.Clear();
    }

    public void StopTrackingHands()
    {
        if (!_trackingHands)
            return;

        _trackingHands = false;
        _hands.OnPlayerSetActiveHand -= OnActiveHandChanged;
        _hands.OnPlayerItemAdded -= OnHeldItemChanged;
        _hands.OnPlayerItemRemoved -= OnHeldItemChanged;
        _hands.OnPlayerHandsAdded -= OnHandsAdded;
        _hands.OnPlayerHandsRemoved -= OnHandsRemoved;
    }
