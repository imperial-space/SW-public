using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.CustomControls;
using Robust.Client.UserInterface.XAML;

namespace Content.Client.Imperial.Medieval.Trading;

[GenerateTypedNameReferences]
public sealed partial class TradingUnitSellWindow : DefaultWindow
{
    public event Action<int>? OnConfirm;

    public TradingUnitSellWindow(string itemName, int price, int maximumAmount)
    {
        RobustXamlLoader.Load(this);
        Prompt.Text = Loc.GetString(
            "trading-ui-unit-sell-question",
            ("item", itemName),
            ("price", price));
        AmountSlider.MinValue = 1;
        AmountSlider.MaxValue = maximumAmount;
        AmountSlider.Value = maximumAmount;
        ConfirmButton.OnPressed += _ =>
        {
            OnConfirm?.Invoke(AmountSlider.Value);
            Close();
        };
    }
}
