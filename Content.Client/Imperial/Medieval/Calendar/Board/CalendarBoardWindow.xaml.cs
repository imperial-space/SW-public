using System;
using Content.Client.Imperial.Medieval.Calendar.Board.Elements;
using Content.Client.Imperial.Medieval.Factions.UI.Elements;
using Content.Shared.Imperial.Medieval.Calendar;
using Robust.Client.AutoGenerated;
using Robust.Client.Player;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.CustomControls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.GameObjects;
using Robust.Shared.IoC;
using Robust.Shared.Localization;

namespace Content.Client.Imperial.Medieval.Calendar.Board;

[GenerateTypedNameReferences]
public sealed partial class CalendarBoardWindow : DefaultWindow
{
    [Dependency] private readonly IEntityManager _entMan = default!;
    [Dependency] private readonly IPlayerManager _playerManager = default!;

    public EntityUid Owner;

    public Action<string, string, string>? OnCreateAnnouncement;
    public Action<Guid>? OnDeleteAnnouncement;

    private AnnouncementCreateWindow? _createWindow;

    public CalendarBoardWindow()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        TabContainer.SetTabTitle(WantedTab, Loc.GetString("calendar-board-tab-wanted"));
        TabContainer.SetTabTitle(CalendarTab, Loc.GetString("calendar-board-tab-calendar"));
        TabContainer.SetTabTitle(AnnouncementsTab, Loc.GetString("calendar-board-tab-announcements"));

        // Устанавливаем названия для новых вложенных вкладок
        TabContainer.SetTabTitle(DayDeckTab, Loc.GetString("calendar-board-tab-days"));
        TabContainer.SetTabTitle(NightDeckTab, Loc.GetString("calendar-board-tab-nights"));

        CreateAnnouncementButton.OnPressed += _ =>
        {
            if (_createWindow != null && _createWindow.IsOpen)
            {
                _createWindow.MoveToFront();
                return;
            }

            _createWindow = new AnnouncementCreateWindow();
            _createWindow.OnSubmit += (title, desc, author) =>
            {
                OnCreateAnnouncement?.Invoke(title, desc, author);
            };
            _createWindow.OpenCentered();
        };
    }

    public void Populate(CalendarBoardBoundUserInterfaceState state)
    {
        WantedGrid.RemoveAllChildren();
        foreach (var item in state.Wanted)
        {
            var entry = new WantedDeskEntry(item.Value);
            WantedGrid.AddChild(entry);
        }


        DayCalendarGrid.RemoveAllChildren();
        if (state.DayDeck != null)
        {
            var daysCount = state.DayDeck.Count;
            for (var i = 0; i < daysCount; i++)
            {
                var isCurrent = i == (state.CurrentCycle % daysCount);

                var entry = new CalendarDayEntry(i + 1, state.DayDeck[i], isCurrent, "calendar-board-day");
                DayCalendarGrid.AddChild(entry);
            }
        }

        NightCalendarGrid.RemoveAllChildren();
        if (state.NightDeck != null)
        {
            var nightsCount = state.NightDeck.Count;
            for (var i = 0; i < nightsCount; i++)
            {
                var isCurrent = i == (state.CurrentCycle % nightsCount);

                var entry = new CalendarDayEntry(i + 1, state.NightDeck[i], isCurrent, "calendar-board-night");
                NightCalendarGrid.AddChild(entry);
            }
        }

        var localEntity = _playerManager.LocalSession?.AttachedEntity;
        var localNetEntity = localEntity != null ? _entMan.GetNetEntity(localEntity.Value) : (NetEntity?)null;

        AnnouncementsList.RemoveAllChildren();
        foreach (var ann in state.Announcements)
        {
            var canDelete = localNetEntity != null && ann.AuthorId == localNetEntity;

            var entry = new AnnouncementEntry(ann, canDelete);
            entry.OnDelete += id => OnDeleteAnnouncement?.Invoke(id);
            AnnouncementsList.AddChild(entry);
        }

        var canCreate = state.Announcements.Count < 3;
        CreateAnnouncementButton.Disabled = !canCreate;
    }

    public override void Close()
    {
        base.Close();
        _createWindow?.Close();
    }
}
