/// <summary>
///     imperial medieval - workbench crafting window. Looks per workbench: <see cref="MedievalWorkbenchTheme"/>.
/// </summary>
[GenerateTypedNameReferences]
public sealed partial class MedievalWorkbenchMenu : MedievalWindow
{
    [Dependency] private readonly IEntityManager _entMan = default!;
    [Dependency] private readonly IPrototypeManager _prototype = default!;
    [Dependency] private readonly IResourceCache _resCache = default!;

    private static readonly Vector2 RowIconSize = new(32, 32);
    private static readonly StyleBoxFlat SearchBox = SearchStyle();

    // brighter than MedievalUiStyle.Warning to stay readable on dark tags
    private static readonly Color MissingColor = Color.FromHex("#e0603a");

    // recipes that can't be made yet
    private static readonly Color UnavailableText = Color.FromHex("#857a6c");
    private static readonly Color UnavailableIcon = new(0.8f, 0.8f, 0.8f, 0.7f);

    public event Action<ProtoId<CP14WorkbenchRecipePrototype>>? OnCraft;

    private readonly SpriteSystem _sprite;

    private MedievalWorkbenchTheme _theme;
    private string? _themeId;

    private CP14WorkbenchUiRecipesState? _state;
    private string? _shownRecipes;
    private ProtoId<CP14WorkbenchRecipePrototype>? _selected;

    private readonly List<RecipeRow> _rows = new();
    private readonly List<(Control Header, bool Craftable)> _headers = new();

    public MedievalWorkbenchMenu()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        _sprite = _entMan.System<SpriteSystem>();

        TitleFont = MedievalUiStyle.TitleFont(_resCache);
        MaterialsLabel.FontOverride = MedievalUiStyle.TextFont(_resCache);
        MaterialsLabel.FontColorOverride = MedievalUiStyle.Gold;
        HintLabel.FontColorOverride = MedievalUiStyle.TextFaded;
        Divider.Color = MedievalUiStyle.Border;
        MedievalUiStyle.ApplyTextFont(_resCache, CraftButton);

        SearchBar.StyleBoxOverride = SearchBox;
        UseMedievalScrollBar(RecipesScroll);
        UseMedievalScrollBar(DescriptionScroll);
        UseMedievalScrollBar(MaterialsScroll);

        SearchBar.OnTextChanged += _ => ApplySearch();
        CraftButton.OnPressed += _ =>
        {
            if (_selected is { } selected)
                OnCraft?.Invoke(selected);
        };

        _theme = MedievalWorkbenchTheme.Plain();
        ApplyTheme();
    }

    private static StyleBoxFlat SearchStyle()
    {
        var box = new StyleBoxFlat
        {
            BackgroundColor = MedievalUiStyle.Inset,
            BorderColor = MedievalUiStyle.Border,
            BorderThickness = new Thickness(1),
        };
        box.SetContentMarginOverride(StyleBox.Margin.Horizontal, 8);
        box.SetContentMarginOverride(StyleBox.Margin.Vertical, 4);
        return box;
    }

    private static void UseMedievalScrollBar(ScrollContainer scroll)
    {
        // ScrollContainer creates its own scrollbars
        foreach (var child in scroll.Children)
        {
            if (child is VScrollBar bar)
                bar.AddStyleClass(StyleNano.MedievalScrollBarClass);
        }
    }

    public void SetWorkbench(EntityUid workbench)
    {
        if (!_entMan.TryGetComponent<MetaDataComponent>(workbench, out var meta))
            return;

        Title = Capitalize(meta.EntityName);
    }

    public void UpdateState(CP14WorkbenchUiRecipesState state)
    {
        _state = state;

        if (_themeId != state.Theme)
        {
            _themeId = state.Theme;
            _theme = MedievalWorkbenchTheme.Get(state.Theme, _resCache);
            ApplyTheme();
            _shownRecipes = null; // rows use theme colours
        }

        // rebuild only when recipes or craftability change, not on every count refresh
        var signature = string.Join(';', state.Recipes.Select(r => r.ProtoId.Id + (r.Craftable ? "+" : "-")));
        if (signature != _shownRecipes)
        {
            _shownRecipes = signature;
            RebuildList(state);
        }

        var keep = _selected is { } selected && state.Recipes.Any(r => r.ProtoId.Id == selected.Id);
        if (!keep)
        {
            _selected = null;
            if (state.Recipes.Count > 0)
                _selected = state.Recipes.FirstOrDefault(r => r.Craftable, state.Recipes[0]).ProtoId;
        }

        ShowSelected();
    }

    private void ApplyTheme()
    {
        if (_theme.Header != null)
        {
            WindowHeader.PanelOverride = _theme.Header;
            WindowHeader.MinSize = new Vector2(0, _theme.HeaderHeight);
        }

        ListPanel.PanelOverride = _theme.List;
        DetailsPanel.PanelOverride = _theme.Details;
        PreviewPanel.PanelOverride = _theme.Preview;
    }

    private void RebuildList(CP14WorkbenchUiRecipesState state)
    {
        RecipesBox.RemoveAllChildren();
        _rows.Clear();
        _headers.Clear();

        AddGroup(state.Recipes.Where(r => r.Craftable).ToList(), true, "medieval-workbench-can-craft");
        AddGroup(state.Recipes.Where(r => !r.Craftable).ToList(), false, "medieval-workbench-cannot-craft");

        ApplySearch();
    }

    private void AddGroup(List<CP14WorkbenchUiRecipesEntry> entries, bool craftable, string title)
    {
        if (entries.Count == 0)
            return;

        var header = new BoxContainer
        {
            Orientation = BoxContainer.LayoutOrientation.Vertical,
            Margin = new Thickness(4, _headers.Count == 0 ? 0 : 6, 8, 4),
        };
        var label = new Label
        {
            Text = Loc.GetString(title),
            FontOverride = MedievalUiStyle.TextFont(_resCache),
            FontColorOverride = craftable ? MedievalUiStyle.Gold : MedievalUiStyle.TextFaded,
        };
        header.AddChild(label);
        header.AddChild(new HLine
        {
            Color = craftable ? MedievalUiStyle.Border : MedievalUiStyle.BorderDisabled,
            Thickness = 1,
            Margin = new Thickness(0, 2, 0, 0),
        });
        RecipesBox.AddChild(header);
        _headers.Add((header, craftable));

        foreach (var entry in entries)
        {
            if (!_prototype.TryIndex(entry.ProtoId, out var recipe))
                continue;

            var row = new RecipeRow(entry, RecipeName(recipe), RecipeIcon(recipe), RecipeIconColor(recipe), _theme.Selected);
            row.OnPressed += _ =>
            {
                _selected = entry.ProtoId;
                ShowSelected();
            };

            RecipesBox.AddChild(row);
            _rows.Add(row);
        }
    }

    private void ApplySearch()
    {
        var search = SearchBar.Text.Trim();

        foreach (var row in _rows)
            row.Visible = search.Length == 0 || row.RecipeName.Contains(search, StringComparison.CurrentCultureIgnoreCase);

        foreach (var (header, craftable) in _headers)
            header.Visible = _rows.Any(r => r.Visible && r.Entry.Craftable == craftable);
    }

    private void ShowSelected()
    {
        foreach (var row in _rows)
            row.SetSelected(_selected is { } s && row.Entry.ProtoId.Id == s.Id);

        MaterialsBox.RemoveAllChildren();

        CP14WorkbenchUiRecipesEntry? entry = null;
        if (_state != null && _selected is { } selected)
        {
            foreach (var e in _state.Recipes)
            {
                if (e.ProtoId.Id == selected.Id)
                {
                    entry = e;
                    break;
                }
            }
        }

        if (entry == null || _state == null || !_prototype.TryIndex(entry.Value.ProtoId, out var recipe))
        {
            ItemView.Texture = null;
            ItemName.SetMessage(string.Empty);
            ItemDescription.SetMessage(string.Empty);
            CraftButton.Disabled = true;
            return;
        }

        // RichTextLabel so long names wrap; same font as MedievalUiStyle.TitleFont
        ItemName.SetMessage(
            FormattedMessage.FromMarkupOrThrow($"[font=\"Vinque\" size=18]{FormattedMessage.EscapeText(RecipeName(recipe))}[/font]"),
            defaultColor: MedievalUiStyle.Gold);
        ItemDescription.SetMessage(FormattedMessage.FromUnformatted(
                _prototype.TryIndex(recipe.Result, out EntityPrototype? result) ? result.Description : string.Empty),
            defaultColor: MedievalUiStyle.TextFaded);

        ItemView.Texture = RecipeIcon(recipe);
        ItemView.TextureScale = new Vector2(2, 2);
        ItemView.ModulateSelfOverride = null;
        if (_prototype.TryIndex(recipe.IconOverride ?? recipe.Result, out EntityPrototype? iconProto) &&
            iconProto.TryGetComponent<SpriteComponent>(out var sprite, _entMan.ComponentFactory))
        {
            ItemView.ModulateSelfOverride = sprite.Color;
            ItemView.TextureScale = Vector2.Min(sprite.Scale * 2, new Vector2(2.5f, 2.5f));
        }

        foreach (var (protoId, need) in recipe.Entities)
        {
            if (!_prototype.TryIndex(protoId, out EntityPrototype? proto))
                continue;

            var have = _state.PlacedEntities.GetValueOrDefault(protoId.Id);
            MaterialsBox.AddChild(MaterialRow(proto.Name, _sprite.GetPrototypeIcon(proto.ID).Default, have, need));
        }

        foreach (var (stackId, need) in recipe.Stacks)
        {
            if (!_prototype.TryIndex(stackId, out StackPrototype? stack))
                continue;

            var have = _state.PlacedStacks.GetValueOrDefault(stackId.Id);
            var icon = stack.Icon != null ? _sprite.Frame0(stack.Icon) : null;
            MaterialsBox.AddChild(MaterialRow(Loc.GetString(stack.Name), icon, have, need));
        }

        CraftButton.Disabled = !entry.Value.Craftable;
    }

    private Control MaterialRow(string name, Texture? icon, int have, int need)
    {
        var enough = have >= need;

        var box = new BoxContainer
        {
            Orientation = BoxContainer.LayoutOrientation.Horizontal,
            SeparationOverride = 6,
        };
        box.AddChild(new TextureRect
        {
            Texture = icon,
            SetSize = RowIconSize,
            Stretch = TextureRect.StretchMode.KeepCentered,
            VerticalAlignment = VAlignment.Center,
        });
        box.AddChild(new Label
        {
            Text = Capitalize(name),
            HorizontalExpand = true,
            ClipText = true,
            VerticalAlignment = VAlignment.Center,
            FontColorOverride = MedievalUiStyle.Text,
        });

        var font = MedievalUiStyle.TextFont(_resCache);
        box.AddChild(new Label
        {
            Text = Math.Min(have, 999).ToString(),
            FontOverride = font,
            FontColorOverride = enough ? MedievalUiStyle.GoldBright : MissingColor,
            VerticalAlignment = VAlignment.Center,
        });
        box.AddChild(new Label
        {
            Text = $" / {need}",
            FontOverride = font,
            FontColorOverride = MedievalUiStyle.Text,
            VerticalAlignment = VAlignment.Center,
        });

        box.AddChild(new PanelContainer
        {
            SetWidth = 3,
            Visible = !enough,
            PanelOverride = new StyleBoxFlat { BackgroundColor = MissingColor },
        });

        return new PanelContainer
        {
            PanelOverride = _theme.Material,
            MinHeight = 36,
            Children = { box },
        };
    }

    private string RecipeName(CP14WorkbenchRecipePrototype recipe)
    {
        return _prototype.TryIndex(recipe.Result, out EntityPrototype? result) ? Capitalize(result.Name) : recipe.ID;
    }

    private Texture? RecipeIcon(CP14WorkbenchRecipePrototype recipe)
    {
        var id = recipe.IconOverride ?? recipe.Result;
        return _prototype.HasIndex(id) ? _sprite.GetPrototypeIcon(id).Default : null;
    }

    private Color RecipeIconColor(CP14WorkbenchRecipePrototype recipe)
    {
        if (_prototype.TryIndex(recipe.IconOverride ?? recipe.Result, out EntityPrototype? proto) &&
            proto.TryGetComponent<SpriteComponent>(out var sprite, _entMan.ComponentFactory))
            return sprite.Color;

        return Color.White;
    }

    // Substring, not text[1..] or char + string: span overloads are sandbox-blocked
    private static string Capitalize(string text)
    {
        return text.Length > 0 ? text.Substring(0, 1).ToUpper() + text.Substring(1) : text;
    }

    private sealed class RecipeRow : ContainerButton
    {
        private static readonly StyleBoxFlat NormalBox = new() { BackgroundColor = Color.Transparent };
        private static readonly StyleBoxFlat HoverBox = new() { BackgroundColor = MedievalUiStyle.BackgroundHover.WithAlpha(0.5f) };

        public readonly CP14WorkbenchUiRecipesEntry Entry;
        public readonly string RecipeName;

        private readonly StyleBoxFlat _selectedBox;
        private readonly Label _name;
        private bool _selected;

        public RecipeRow(CP14WorkbenchUiRecipesEntry entry, string name, Texture? icon, Color iconColor, Color selected)
        {
            Entry = entry;
            RecipeName = name;

            _selectedBox = new StyleBoxFlat
            {
                BackgroundColor = selected,
                BorderColor = MedievalUiStyle.Gold,
                BorderThickness = new Thickness(3, 0, 0, 0),
            };

            var box = new BoxContainer
            {
                Orientation = BoxContainer.LayoutOrientation.Horizontal,
                SeparationOverride = 6,
                Margin = new Thickness(6, 2),
            };
            box.AddChild(new TextureRect
            {
                Texture = icon,
                SetSize = RowIconSize,
                Stretch = TextureRect.StretchMode.KeepCentered,
                ModulateSelfOverride = entry.Craftable ? iconColor : iconColor * UnavailableIcon,
            });
            _name = new Label
            {
                Text = name,
                ClipText = true,
                HorizontalExpand = true,
                VerticalAlignment = VAlignment.Center,
            };
            box.AddChild(_name);
            AddChild(box);

            UpdateLook();
        }

        public void SetSelected(bool selected)
        {
            if (_selected == selected)
                return;

            _selected = selected;
            UpdateLook();
        }

        protected override void DrawModeChanged()
        {
            base.DrawModeChanged();
            UpdateLook();
        }

        private void UpdateLook()
        {
            // called from the base constructor before the fields are set
            if (_name == null || _selectedBox == null)
                return;

            StyleBoxOverride = _selected ? _selectedBox : DrawMode == DrawModeEnum.Hover ? HoverBox : NormalBox;
            _name.FontColorOverride = !Entry.Craftable ? UnavailableText
                : _selected ? MedievalUiStyle.GoldBright
                : MedievalUiStyle.Text;
        }
    }
}
