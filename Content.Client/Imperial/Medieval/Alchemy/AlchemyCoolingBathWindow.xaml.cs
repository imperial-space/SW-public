using Content.Client.UserInterface.Controls;
using Content.Shared.Imperial.Medieval.Alchemy;
using Robust.Client.AutoGenerated;
using Robust.Client.Graphics;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;

namespace Content.Client.Imperial.Medieval.Alchemy;

[GenerateTypedNameReferences]
public sealed partial class AlchemyCoolingBathWindow : FancyWindow
{
    public event Action<int>? OnDurationSelected;

    public AlchemyCoolingBathWindow()
    {
        RobustXamlLoader.Load(this);
    }

    public void UpdateState(AlchemyCoolingBathUiState state)
    {
        DurationButtons.DisposeAllChildren();
        var group = new ButtonGroup();
        foreach (var duration in state.Durations)
        {
            var button = new Button
            {
                Text = duration.ToString(),
                TextAlign = Label.AlignMode.Center,
                ToggleMode = true,
                Group = group,
                Pressed = duration == state.SelectedDuration,
                HorizontalExpand = true,
                Disabled = state.IsProcessing,
            };
            button.StyleClasses.Add("OpenBoth");
            button.OnPressed += _ => OnDurationSelected?.Invoke(duration);
            DurationButtons.AddChild(button);
        }

        var disabled = state.IsProcessing || state.Contents.Length == 0;
        BusyOverlay.Visible = state.IsProcessing;
        StartButton.Disabled = disabled || state.SelectedDuration <= 0;
        EjectButton.Disabled = disabled;
        ContentsPanel.PanelOverride = new StyleBoxFlat
        {
            BackgroundColor = Color.FromHex(state.IsProcessing ? "#245A73" : "#1B1B1E"),
        };
    }
}
