using System.Linq;
using Content.Shared.Imperial.Medieval.GhostSkills;
using Content.Shared.Imperial.Medieval.Skills;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.CustomControls;
using Robust.Client.UserInterface.XAML;
using Robust.Client.Utility;
using Robust.Shared.Prototypes;
using Robust.Shared.Utility;

namespace Content.Client.Imperial.Medieval.Skills.UI;

[GenerateTypedNameReferences]
public sealed partial class GhostSkillsMenu : DefaultWindow
{
    private const float InitialPixelWidth = 1100f;
    private const float MinimumPixelWidth = 1050f;

    private readonly IPrototypeManager _prototypes;
    private readonly Dictionary<string, int> _levels;
    private readonly Dictionary<string, SkillEntry> _entries = new();

    public Action<Dictionary<string, int>>? SavePressed;

    public GhostSkillsMenu(IPrototypeManager prototypes, Dictionary<string, int> levels)
    {
        RobustXamlLoader.Load(this);
        ApplyPixelWidth(UserInterfaceManager.RootControl.UIScale);
        _prototypes = prototypes;
        _levels = SharedSkillsSystem.GetDefaultSkillLevels(prototypes);

        foreach (var (id, level) in levels)
        {
            if (_levels.ContainsKey(id))
                _levels[id] = level;
        }

        Populate();
        SaveButton.OnPressed += _ => Save();
    }

    protected override void UIScaleChanged()
    {
        base.UIScaleChanged();
        ApplyPixelWidth(UIScale);
    }

    private void ApplyPixelWidth(float uiScale)
    {
        MinWidth = MinimumPixelWidth / uiScale;
        SetWidth = InitialPixelWidth / uiScale;
    }

    private void Populate()
    {
        SkillsContainer.RemoveAllChildren();
        _entries.Clear();

        foreach (var skill in _prototypes.EnumeratePrototypes<SkillPrototype>()
                     .OrderBy(skill => Loc.GetString(skill.Name)))
        {
            var level = _levels[skill.ID];
            var icon = skill.Icons[skill.Icons.Keys.Where(value => value <= level).Max()];
            var entry = new SkillEntry(
                skill.ID,
                Loc.GetString(skill.Name),
                level,
                new SpriteSpecifier.Rsi(new ResPath(skill.RsiPath), icon),
                skill.Color,
                _prototypes);

            entry.LevelSet += newLevel => SetLevel(skill.ID, newLevel);
            _entries[skill.ID] = entry;
            SkillsContainer.AddChild(entry);
        }

        RefreshState();
    }

    private void SetLevel(string id, int level)
    {
        if (level is < GhostSkillProfileComponent.MinimumLevel or > GhostSkillProfileComponent.MaximumLevel)
            return;

        var oldLevel = _levels[id];
        _levels[id] = level;
        if (SharedSkillsSystem.GetRemainingPoints(_prototypes, _levels) < 0)
        {
            _levels[id] = oldLevel;
            return;
        }

        _entries[id].Level = level;
        RefreshState();
    }

    private void RefreshState()
    {
        var points = SharedSkillsSystem.GetRemainingPoints(_prototypes, _levels);
        PointsLabel.Text = Loc.GetString("ghost-skills-points", ("points", points));
        SaveButton.Disabled = points < 0;

        foreach (var (id, entry) in _entries)
        {
            var currentLevel = _levels[id];
            entry.DecreaseButton.Disabled = currentLevel <= GhostSkillProfileComponent.MinimumLevel;

            if (currentLevel >= GhostSkillProfileComponent.MaximumLevel)
            {
                entry.IncreaseButton.Disabled = true;
                continue;
            }

            _levels[id] = currentLevel + 1;
            entry.IncreaseButton.Disabled = SharedSkillsSystem.GetRemainingPoints(_prototypes, _levels) < 0;
            _levels[id] = currentLevel;
        }
    }

    private void Save()
    {
        if (SharedSkillsSystem.GetRemainingPoints(_prototypes, _levels) < 0)
            return;

        SavePressed?.Invoke(new(_levels));
    }
}
