    /// <summary>
    /// The look of the book. An empty theme is the common (collegium) one, any other has its own folder of textures that
    /// replace the common ones, see <see cref="FoliantStyle.Tex(IResourceCache, string, string)"/>.
    /// </summary>
    private void ApplyTheme(string theme)
    {
        _theme = theme;
        _palette = FoliantStyle.PaletteOf(theme);

        Cover.PanelOverride = FoliantStyle.Cover(_cache, theme);
        LeftPage.PanelOverride = FoliantStyle.Page(_cache, true, theme);
        RightPage.PanelOverride = FoliantStyle.Page(_cache, false, theme);
        Gutter.PanelOverride = FoliantStyle.Gutter(_cache, theme);
        BookmarkTail.Texture = FoliantStyle.Tex(_cache, theme, "ribbon_tail.png");
        PortraitRing.Texture = FoliantStyle.Tex(_cache, theme, "socket.png");
        RitualHint.FontColorOverride = _palette.Hint;
        SearchBar.StyleBoxOverride = SearchStyle(_palette.SearchLine ?? FoliantStyle.RowLine);

        // the divider has its own knot in some themes
        FillDivider(DividerTop, FoliantStyle.Ink);
        FillDivider(DividerBottom, FoliantStyle.Ink);
        FillDivider(DividerPick, FoliantStyle.Ink);

        var hasMedallion = FoliantStyle.TryTheme(_cache, theme, "medallion.png", out var medallion);
        Medallion.Visible = hasMedallion;
        Medallion.Texture = medallion;
    }

    public void UpdateState(ImperialStoreUpdateState state)
    {
        _listings = state.Listings.ToList();
        _balance = state.Balance;
        _slots = state.Slots;
        _selectable = state.SelectableSchools;
        _allowRefund = state.AllowRefund;

        if (_pickSlot >= _slots.Count)
            _pickSlot = null;

        // the list is rebuilt on every update, keep the place in it
        _restoreScroll ??= SpellsScroll.VScroll;
        _restoreFrames = 2;

        Rebuild();
    }

    protected override void FrameUpdate(FrameEventArgs args)
    {
        base.FrameUpdate(args);

        // the book is kept on the screen
        if (IsMeasureValid && Parent != null)
        {
            var space = Parent.Size;
            var pos = Vector2.Max(Vector2.Min(Position, space - Size), Vector2.Zero);
            if (pos != Position)
                LayoutContainer.SetPosition(this, pos);
        }

        if (_restoreScroll is not { } scroll || --_restoreFrames > 0)
            return;

        SpellsScroll.SetScrollValue(new Vector2(0, scroll));
        _restoreScroll = null;
    }

    public override void Close()
    {
        base.Close();
        _withdrawWindow?.Close();
    }

    private void PageTurn()
    {
        _entMan.System<AudioSystem>().PlayGlobal(PageTurnSound, Filter.Local(), false, AudioParams.Default.WithVolume(-3f));
    }

    private void Rebuild()
    {
        var tabs = BuildTabs();

        if (tabs.All(tab => tab.Category.ID != _category))
            _category = tabs.Count > 0 ? tabs[0].Category.ID : string.Empty;

        var current = tabs.FirstOrDefault(tab => tab.Category.ID == _category);

        RebuildRibbons(tabs);
        RebuildLeft(current);
        RebuildRight();
    }

    private List<Tab> BuildTabs()
    {
        var categories = new Dictionary<string, (ImperialStoreCategoryPrototype Category, string? School)>();

        foreach (var listing in _listings)
        {
            foreach (var id in listing.Categories)
            {
                if (!categories.TryGetValue(id, out var known))
                {
                    if (!_prototype.TryIndex<ImperialStoreCategoryPrototype>(id, out var category))
                        continue;

                    known = (category, null);
                }

                // the school of a category is the school currency its spells cost
                if (known.School == null)
                    known.School = listing.Cost.Keys.Select(key => key.Id).FirstOrDefault(key => ImperialStoreSlots.IsSchool(_prototype, key));

                categories[id] = known;
            }
        }

        return categories.Values
            .OrderBy(entry => entry.Category.Priority)
            .Select(entry => new Tab(entry.Category, entry.School))
            .ToList();
    }

    private Color SchoolColor(string? school)
    {
        if (school == null || !_prototype.TryIndex<ImperialCurrencyPrototype>(school, out var proto))
            return FoliantStyle.Gold;

        return FoliantStyle.School(school, proto.DisplayNameColor);
    }

    private string Amount(string? currency)
    {
        return currency != null && _balance.TryGetValue(currency, out var amount) ? amount.ToString() : "0";
    }

    private void RebuildRibbons(List<Tab> tabs)
    {
        Ribbons.RemoveAllChildren();

        foreach (var tab in tabs)
        {
            var color = SchoolColor(tab.School);
            var chosen = tab.Category.ID == _category && _pickSlot == null;
            var ribbon = new FoliantRibbon(
                _cache,
                Loc.GetString(tab.Category.Name),
                tab.School,
                tab.School == null ? " " : Amount(tab.School),
                FoliantStyle.RibbonTint(tab.School, color, _palette.TabSaturation),
                color,
                chosen,
                _theme);

            var id = tab.Category.ID;
            ribbon.OnPressed += _ =>
            {
                if (_category != id || _pickSlot != null)
                    PageTurn();

                _category = id;
                _pickSlot = null;
                Rebuild();
                SpellsScroll.SetScrollValue(Vector2.Zero);
            };

            Ribbons.AddChild(ribbon);
        }
    }

    private void RebuildLeft(Tab tab)
    {
        // while a slot is being filled the page is about the circle only
        Portrait.Visible = _pickSlot == null && tab.Category != null;

        if (tab.Category != null)
        {
            var color = SchoolColor(tab.School);
            PortraitRune.Texture = FoliantStyle.Tex(_cache, tab.School == null ? "rune_none.png" : RuneFile(tab.School));
            PortraitRune.ModulateSelfOverride = color;
            SchoolName.Text = Loc.GetString(tab.Category.Name);

            // the lines of the page take the colour of the school
            var accent = FoliantStyle.Accent(tab.School, color);
            FillDivider(DividerTop, accent);
            SearchBar.StyleBoxOverride = SearchStyle(_palette.SearchLine ?? accent);

            AmountBox.RemoveAllChildren();
            if (tab.School != null)
            {
                AmountBox.AddChild(FoliantStyle.Rune(_cache, tab.School, color, 2));
                AmountBox.AddChild(FoliantStyle.Text(Amount(tab.School), FoliantStyle.Vinque(_cache, 22), FoliantStyle.Ink));
            }
        }

        RebuildSeals();

        var hasSlots = _slots.Count > 0;
        SourceTitle.Visible = hasSlots;
        RitualBox.Visible = hasSlots;

        RebuildRitual();

        RitualHint.Visible = hasSlots && _pickSlot == null;
        RitualHint.Text = Loc.GetString(_slots.Contains(null) ? "foliant-ritual-hint-empty" : "foliant-ritual-hint-full");

        RebuildLinks();
    }

    private static string RuneFile(string school) => FoliantStyle.RuneFile(school);

    /// <summary>A wax seal for every point of archmage, and what they are called.</summary>
    private void RebuildSeals()
    {
        SealsBox.RemoveAllChildren();
        _sealsNote?.Orphan();
        _sealsNote = null;
        LeftBox.Margin = new Thickness(0, PageTop, 0, 0);

        foreach (var (key, amount) in _balance)
        {
            if (!_prototype.TryIndex(key, out var proto) || !proto.DrawSeparately || amount <= 0)
                continue;

            for (var i = 0; i < Math.Min((int) amount, MaxSeals); i++)
            {
                SealsBox.AddChild(FoliantStyle.Seal(_cache, _theme));
            }

            // more than two seals and the name does not fit beside them, it goes under them
            var wrap = amount > 2 && SealsBox.Parent is BoxContainer;
            var note = new Label
            {
                Text = Loc.GetString("foliant-seals"),
                FontOverride = FoliantStyle.Vinque(_cache, 12),
                FontColorOverride = _palette.Hint,
                VerticalAlignment = VAlignment.Center,
                Margin = wrap ? new Thickness(0, 2, 0, 0) : new Thickness(6, 0, 0, 0),
            };

            if (wrap)
            {
                // the note takes a line under the seals, so the page starts higher to keep the links inside the frame
                LeftBox.Margin = new Thickness(0, PageTopTight, 0, 0);
                var parent = (BoxContainer) SealsBox.Parent!;
                parent.AddChild(note);
                note.SetPositionInParent(SealsBox.GetPositionInParent() + 1);
                _sealsNote = note;
            }
            else
            {
                SealsBox.AddChild(note);
            }

            return;
        }
    }

    private void RebuildRitual()
    {
        RitualBox.RemoveAllChildren();

        if (_slots.Count == 0)
            return;

        var sockets = _slots
            .Select(school => new FoliantSocket(
                school,
                SchoolColor(school),
                school == null ? Loc.GetString("foliant-slot-empty") : FoliantStyle.SchoolName(school)))
            .ToList();

        var ritual = new FoliantRitual(_cache, sockets, _pickSlot, _flash, _theme);
        ritual.OnPressed += slot =>
        {
            _pickSlot = _pickSlot == slot ? null : slot;
            Rebuild();
        };

        RitualBox.AddChild(new Control { HorizontalExpand = true });
        RitualBox.AddChild(ritual);
        RitualBox.AddChild(new Control { HorizontalExpand = true });
    }

    private void RebuildLinks()
    {
        LinksBox.RemoveAllChildren();

        var withdrawable = _balance.Where(pair =>
        {
            return _prototype.TryIndex(pair.Key, out var proto) && proto.CanWithdraw && proto.Cash != null;
        }).ToList();

        if (withdrawable.Count > 0)
        {
            var withdraw = new FoliantLink(_cache, _withdrawText) { Disabled = withdrawable.All(pair => pair.Value <= 0) };
            withdraw.OnPressed += _ => OpenWithdraw();
            LinksBox.AddChild(withdraw);
        }

        if (_allowRefund)
        {
            var refund = new FoliantLink(_cache, Loc.GetString("foliant-refund"));
            refund.OnPressed += _ => OnRefund?.Invoke();
            LinksBox.AddChild(refund);
        }
    }

    private void OpenWithdraw()
    {
        if (_withdrawWindow != null && _withdrawWindow.IsOpen)
        {
            _withdrawWindow.MoveToFront();
            return;
        }

        _withdrawWindow = new ImperialStoreWithdrawWindow();
        _withdrawWindow.OpenCentered();

        _withdrawWindow.CreateCurrencyButtons(_balance);
        _withdrawWindow.Title = _withdrawText;
        _withdrawWindow.OnWithdrawAttempt += (_, type, amount) => OnWithdraw?.Invoke(type, amount);
    }

    private void RebuildRight()
    {
        LearnView.Visible = _pickSlot == null;
        PickView.Visible = _pickSlot != null;

        if (_pickSlot is { } slot)
            RebuildPick(slot);
        else
            RebuildSpells();
    }

    // ---- spells

    private void RebuildSpells()
    {
        SpellsBox.RemoveAllChildren();

        var listings = _listings
            .Where(listing => listing.Categories.Contains(_category))
            .Where(MatchesSearch)
            .OrderBy(listing => listing.Priority)
            .ThenBy(listing => listing.Cost.Values.Sum())
            .ThenBy(listing => listing.ID);

        foreach (var listing in listings)
        {
            SpellsBox.AddChild(SpellRow(listing));
        }

        if (SpellsBox.ChildCount == 0)
        {
            // a page with no records is not left blank
            SpellsBox.AddChild(new Label
            {
                Text = Loc.GetString(string.IsNullOrEmpty(_search) ? "foliant-empty" : "foliant-empty-search"),
                FontOverride = FoliantStyle.Vinque(_cache, 15),
                FontColorOverride = _palette.Hint,
                HorizontalAlignment = HAlignment.Center,
                Margin = new Thickness(0, 60, 0, 0),
            });
        }
    }

    private bool MatchesSearch(ImperialListingData listing)
    {
        if (string.IsNullOrEmpty(_search))
            return true;

        return ImperialListingLocalisationHelpers.GetLocalisedNameOrEntityName(listing, _prototype).ToLowerInvariant().Contains(_search)
            || ImperialListingLocalisationHelpers.GetLocalisedDescriptionOrEntityDescription(listing, _prototype).ToLowerInvariant().Contains(_search);
    }

    private Control SpellRow(ImperialListingData listing)
    {
        var name = ImperialListingLocalisationHelpers.GetLocalisedNameOrEntityName(listing, _prototype);
        var description = ImperialListingLocalisationHelpers.GetLocalisedDescriptionOrEntityDescription(listing, _prototype);

        // a square plate, the icons of the spells are round in some and square in other
        var plate = new Control { MinSize = new Vector2(48, 48), VerticalAlignment = VAlignment.Top, Margin = new Thickness(0, 6, 0, 0) };
        plate.AddChild(new TextureRect { Texture = FoliantStyle.Tex(_cache, _theme, "plate.png"), Stretch = TextureRect.StretchMode.Keep });
        plate.AddChild(new TextureRect
        {
            Texture = IconOf(listing),
            Stretch = TextureRect.StretchMode.KeepCentered,
            Margin = new Thickness(8),
        });

        var title = new RichTextLabel();
        title.SetMarkupPermissive($"[font=\"Vinque\" size=15][color={FoliantStyle.InkRed.ToHexNoAlpha()}]{FormattedMessage.EscapeText(name)}[/color][/font]");

        var text = new RichTextLabel { Margin = new Thickness(0, 2, 0, 0) };
        text.SetMessage(description, defaultColor: FoliantStyle.Ink);

        var buy = BuyButton(listing);
        buy.HorizontalAlignment = HAlignment.Right;
        buy.Margin = new Thickness(0, 6, 0, 0);

        // the text has a fixed width, or it would be as wide as the page and push the button out
        var words = new BoxContainer
        {
            Orientation = BoxContainer.LayoutOrientation.Vertical,
            SetWidth = SpellTextWidth,
            Margin = new Thickness(0, 4, 0, 0),
        };
        words.AddChild(title);
        words.AddChild(text);
        words.AddChild(buy);

        var line = new BoxContainer { Orientation = BoxContainer.LayoutOrientation.Horizontal, SeparationOverride = 12 };
        line.AddChild(plate);
        line.AddChild(words);

        var row = new BoxContainer { Orientation = BoxContainer.LayoutOrientation.Vertical };
        row.AddChild(line);
        row.AddChild(new PanelContainer
        {
            PanelOverride = new StyleBoxTexture { Texture = FoliantStyle.Tex(_cache, "dots.png"), Mode = StyleBoxTexture.StretchMode.Tile },
            MinHeight = 1,
            Margin = new Thickness(0, 8, 0, 8),
        });

        var lit = new FoliantRow(SpellsScroll);
        lit.AddChild(row);
        return lit;
    }

    private FoliantButton BuyButton(ImperialListingData listing)
    {
        var button = new FoliantButton(_cache, Loc.GetString("foliant-learn"), _theme);
        var enough = true;

        foreach (var (currency, price) in listing.Cost)
        {
            var has = _balance.TryGetValue(currency, out var amount) && amount >= price;
            enough &= has;

            if (!_prototype.TryIndex(currency, out var proto) || proto.IgnoreInPurchaseButton)
                continue;

            button.CostBox.AddChild(FoliantStyle.Text(price.ToString(), null, has ? FoliantStyle.Price : FoliantStyle.PriceMissing));
            button.CostBox.AddChild(FoliantStyle.Rune(_cache, currency, FoliantStyle.School(currency, proto.DisplayNameColor), 1));
        }

        if (listing.Cost.Count < 1)
            button.CostBox.AddChild(FoliantStyle.Text(Loc.GetString("store-currency-free"), null, FoliantStyle.Price));

        var stationTime = _timing.CurTime.Subtract(_ticker.RoundStartTimeSpan);
        button.Disabled = !enough || listing.RestockTime > stationTime;
        button.OnPressed += _ => OnBuy?.Invoke(listing);
        return button;
    }

    private Texture? IconOf(ImperialListingData listing)
    {
        if (_icons.TryGetValue(listing.ID, out var known))
            return known;

        Texture? texture = null;

        if (listing.Icon != null)
            texture = _sprite.Frame0(listing.Icon);

        if (texture == null && listing.ProductEntity != null)
        {
            texture = _sprite.GetPrototypeIcon(listing.ProductEntity).Default;
        }
        else if (texture == null && listing.ProductAction != null)
        {
            var actionId = _entMan.Spawn(listing.ProductAction);
            var action = _entMan.System<ActionsSystem>().GetAction(actionId);
            if (action?.Comp.Icon != null)
                texture = _sprite.Frame0(action.Value.Comp.Icon);

            _entMan.DeleteEntity(actionId);
        }

        _icons[listing.ID] = texture;
        return texture;
    }

    // ---- gifts of the schools for a slot

    private void RebuildPick(int slot)
    {
        PickBox.RemoveAllChildren();
        PickLinks.RemoveAllChildren();

        foreach (var (school, _) in ImperialStoreSlots.GetSchools(_prototype))
        {
            if (!_prototype.TryIndex<ImperialCurrencyPrototype>(school, out var proto))
                continue;

            PickBox.AddChild(SchoolRow(slot, school, proto));
        }

        if (_slots[slot] != null)
        {
            var clear = new FoliantLink(_cache, Loc.GetString("foliant-pick-clear"));
            clear.OnPressed += _ =>
            {
                OnSetSlot?.Invoke(slot, null);
                _pickSlot = null;
                Rebuild();
            };
            PickLinks.AddChild(clear);
        }
    }

    private Control SchoolRow(int slot, string school, ImperialCurrencyPrototype proto)
    {
        var chosen = _slots[slot] == school;
        var open = chosen || _selectable.Contains(school);
        var color = FoliantStyle.School(school, proto.DisplayNameColor);

        var stripe = new PanelContainer
        {
            PanelOverride = FoliantStyle.Flat(open ? color : FoliantStyle.RowLine, open ? color : FoliantStyle.RowLine, 0),
            MinWidth = 6,
        };

        var rune = FoliantStyle.Rune(_cache, school, open ? color : FoliantStyle.RowLine, 2);
        rune.Margin = new Thickness(14, 0, 14, 0);

        var name = new Label
        {
            Text = FoliantStyle.SchoolName(school),
            FontOverride = FoliantStyle.Vinque(_cache, 17),
            FontColorOverride = open ? FoliantStyle.InkRed : FoliantStyle.InkFaded,
            VerticalAlignment = VAlignment.Center,
            HorizontalExpand = true,
        };

        var line = new BoxContainer { Orientation = BoxContainer.LayoutOrientation.Horizontal };
        line.AddChild(stripe);
        line.AddChild(rune);
        line.AddChild(name);

        if (open && !chosen)
        {
            var pick = new FoliantButton(_cache, Loc.GetString("foliant-pick-select"), _theme)
            {
                VerticalAlignment = VAlignment.Center,
                Margin = new Thickness(0, 6, 8, 6),
            };
            pick.OnPressed += _ =>
            {
                _flash = (slot, color, _timing.RealTime);
                OnSetSlot?.Invoke(slot, school);
                _pickSlot = null;
                Rebuild();
            };
            line.AddChild(pick);
        }

        var panel = new PanelContainer
        {
            PanelOverride = FoliantStyle.Flat(chosen ? FoliantStyle.RowHover : Color.Transparent, chosen ? FoliantStyle.Ink : FoliantStyle.RowLine, 1),
            MinHeight = 54,
            ToolTip = open ? null : Loc.GetString("foliant-pick-lack"),
        };
        panel.AddChild(line);
        return panel;
    }
