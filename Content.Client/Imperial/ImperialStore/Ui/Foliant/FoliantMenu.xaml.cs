        {
            _search = args.Text.Trim().ToLowerInvariant();
            RebuildSpells();
            SpellsScroll.SetScrollValue(Vector2.Zero);
        };
    }

    /// <summary>
    /// A stylesheet of a control replaces the common one, so the rules of the common one are taken along and the
    /// own rules come last.
    /// </summary>
    private Stylesheet WithRules(params StyleRule[] own)
    {
        var rules = new List<StyleRule>();
        if (_ui.Stylesheet != null)
            rules.AddRange(_ui.Stylesheet.Rules);

        rules.AddRange(own);
        return new Stylesheet(rules);
    }

    /// <summary>The scroll bar of the page is a thin strip of ink instead of the grey bar of the interface.</summary>
    private Stylesheet ScrollStyle()
    {
        StyleBoxFlat Grabber(Color color) => new()
        {
            BackgroundColor = color,
            ContentMarginLeftOverride = 5,
            ContentMarginTopOverride = 5,
        };

        return WithRules(
            new StyleRule(new SelectorElement(typeof(VScrollBar), null, null, null),
                new[] { new StyleProperty(ScrollBar.StylePropertyGrabber, Grabber(FoliantStyle.RowLine.WithAlpha(0.8f))) }),
            new StyleRule(new SelectorElement(typeof(VScrollBar), null, null, new[] { ScrollBar.StylePseudoClassHover }),
                new[] { new StyleProperty(ScrollBar.StylePropertyGrabber, Grabber(FoliantStyle.InkFaded)) }),
            new StyleRule(new SelectorElement(typeof(VScrollBar), null, null, new[] { ScrollBar.StylePseudoClassGrabbed }),
                new[] { new StyleProperty(ScrollBar.StylePropertyGrabber, Grabber(FoliantStyle.Ink)) }));
    }

    /// <summary>The search field is written with ink on the page, not a dark hole in it.</summary>
    private Stylesheet SearchTextStyle()
    {
        return WithRules(
            new StyleRule(new SelectorElement(typeof(LineEdit), null, null, null),
                new[]
                {
                    new StyleProperty("font-color", FoliantStyle.Ink),
                    new StyleProperty(LineEdit.StylePropertyCursorColor, FoliantStyle.Ink),
                    new StyleProperty(LineEdit.StylePropertySelectionColor, FoliantStyle.RowHover),
                }),
            new StyleRule(new SelectorElement(typeof(LineEdit), null, null, new[] { LineEdit.StylePseudoClassPlaceholder }),
                new[] { new StyleProperty("font-color", FoliantStyle.InkFaded) }));
    }

    private static StyleBoxFlat SearchStyle(Color border)
    {
        // a little darker than the page, with a thin line of the colour of the school
        var box = FoliantStyle.Flat(FoliantStyle.SearchFill, border, 1);
        box.SetContentMarginOverride(StyleBox.Margin.Horizontal, 8);
        box.SetContentMarginOverride(StyleBox.Margin.Vertical, 4);
        return box;
    }

    /// <summary>A line with a diamond in the middle.</summary>
    private void FillDivider(BoxContainer box, Color color)
    {
        box.RemoveAllChildren();

        var left = new HLine { Color = color, Thickness = 1, HorizontalExpand = true, VerticalAlignment = VAlignment.Center };
        var right = new HLine { Color = color, Thickness = 1, HorizontalExpand = true, VerticalAlignment = VAlignment.Center };
        var diamond = new TextureRect
        {
            Texture = FoliantStyle.Tex(_cache, _theme, "diamond.png"),
            Stretch = TextureRect.StretchMode.Keep,
            VerticalAlignment = VAlignment.Center,
        };

        box.AddChild(left);
        box.AddChild(diamond);
        box.AddChild(right);
    }

